-- Script to creating the database schema for the ShopinGo e-commerce project
-- Creating the enum role type, if it doesn't exist
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'role') THEN
    CREATE TYPE public.role AS ENUM ('admin', 'customer', 'manager');
  END IF;
END$$;

-- Creating the addresses table
CREATE TABLE IF NOT EXISTS public.addresses (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cep TEXT NOT NULL,
  city TEXT NOT NULL,
  uf TEXT NOT NULL,
  street TEXT NOT NULL,
  number TEXT NOT NULL,
  neighborhood TEXT NOT NULL,
  complement TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Ceating the profiles table
CREATE TABLE IF NOT EXISTS public.profiles (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  name TEXT NOT NULL,
  updated_at TIMESTAMPTZ,
  role public.role NOT NULL DEFAULT 'customer',
  phone TEXT,
  user_id UUID NOT NULL UNIQUE,
  address_id BIGINT,
  email TEXT NOT NULL UNIQUE,
  CONSTRAINT profile_user_id_fkey FOREIGN KEY (user_id) REFERENCES auth.users (id) ON DELETE CASCADE,
  CONSTRAINT profiles_address_id_fkey FOREIGN KEY (address_id) REFERENCES addresses (id) ON DELETE CASCADE
);

-- Creating the products table
CREATE TABLE IF NOT EXISTS public.products (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  price DOUBLE PRECISION,
  description TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ,
  image_url TEXT[],
  active BOOLEAN,
  stripe_product_id TEXT NOT NULL UNIQUE,
  category TEXT NOT NULL,
  brand TEXT,
  color TEXT,
  model TEXT,
  warranty TEXT,
  size TEXT
);

-- Creating the orders table
CREATE TABLE IF NOT EXISTS public.orders (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ,
  payment_method TEXT NOT NULL,
  status TEXT NOT NULL,
  total_price DOUBLE PRECISION NOT NULL,
  address_street TEXT NOT NULL,
  address_number TEXT NOT NULL,
  address_complement TEXT NOT NULL,
  address_neighborhood TEXT NOT NULL,
  address_city TEXT NOT NULL,
  address_state TEXT NOT NULL,
  address_zipcode TEXT NOT NULL,
  profile_id BIGINT NOT NULL,
  shipping_price DOUBLE PRECISION,
  shipping_provider TEXT NOT NULL,
  CONSTRAINT orders_profile_id_fkey FOREIGN KEY (profile_id) REFERENCES profiles (id) ON UPDATE CASCADE ON DELETE CASCADE
);

-- Creating the orders_items table
CREATE TABLE IF NOT EXISTS public.orders_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id BIGINT NOT NULL,
  product_id TEXT NOT NULL,
  quantity BIGINT NOT NULL,
  price DOUBLE PRECISION NOT NULL,
  CONSTRAINT orders_items_order_id_fkey FOREIGN KEY (order_id) REFERENCES orders (id) ON UPDATE CASCADE ON DELETE CASCADE
);

-- Creating the reviews table
CREATE TABLE IF NOT EXISTS public.reviews (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  order_item_id BIGINT NOT NULL,
  profile_id BIGINT NOT NULL,
  rating BIGINT,
  comment TEXT,
  rated BOOLEAN,
  updated_at TIMESTAMPTZ,
  CONSTRAINT reviews_order_item_id_fkey FOREIGN KEY (order_item_id) REFERENCES orders_items (id) ON UPDATE CASCADE ON DELETE CASCADE,
  CONSTRAINT reviews_profile_id_fkey FOREIGN KEY (profile_id) REFERENCES profiles (id) ON UPDATE CASCADE ON DELETE CASCADE
);
